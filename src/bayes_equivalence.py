"""
CALM-Stroke: Bayesian bootstrap posterior of paired AUC differences
with a region of practical equivalence (ROPE).

Input : out-of-fold predictions in the public repository
        https://github.com/jouninLRMD/CALM-Stroke (results/oof, results/explain)
Output: bayes_rope.csv, numbers_bayes.tex,
        fig_bayes_rope.pdf / .png (two panels, supplement) and
        fig_bayes_rope_col.pdf / .png (one column, main text)

Method
------
Bayesian bootstrap (Rubin, 1981): patient weights w ~ Dirichlet(1,...,1).
For each draw the weighted AUC of every model is computed on the SAME weights,
so the posterior of Delta AUC respects the pairing. With a ROPE of +/- delta
we report P(Delta < -delta), P(|Delta| <= delta) and P(Delta > delta)
(Kruschke, 2018; Benavoli et al., 2017).

Usage: python src/bayes_equivalence.py [repo root] [output dir]
       (defaults: current directory and results/paper)
"""
import sys, os, glob
import numpy as np, pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

REPO = sys.argv[1] if len(sys.argv) > 1 else "."
RESD = os.environ.get("CALM_RESULTS", os.path.join(REPO, "results"))
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(RESD, "paper")
os.makedirs(OUT, exist_ok=True)
NDRAW, SEED, ROPES = 4000, 20261117, (0.01, 0.02, 0.03)
ROPE = 0.02  # primary margin

coh = pd.read_csv(f"{RESD}/cohort_all.csv")
coh = coh[coh.labelled == True][["participant_id", "y_poor"]].dropna()


def seed_avg(pattern):
    fs = sorted(glob.glob(f"{RESD}/oof/{pattern}"))
    d = pd.concat([pd.read_csv(f)[["participant_id", "p_gt2"]] for f in fs])
    return d.groupby("participant_id").p_gt2.mean(), len(fs)


models = {}
spec = [
    ("CALM-Stroke", "calm25d__cv5__s*.csv"),
    ("2.5D MIL + anchor", "slice25d__cv5__s*.csv"),
    ("2.5D MIL + lesion anchor", "slice25d_lesanchor__cv5__s*.csv"),
    ("CALM-Stroke, no auxiliary tasks", "calm25d_noaux__cv5__s*.csv"),
    ("CALM-Stroke, no lesion head", "calm25d_noseg__cv5__s*.csv"),
    ("CALM-Stroke, no anchor", "calm25d_noanchor__cv5__s*.csv"),
    ("CALM-3D (from scratch)", "calm__cv5__s*.csv"),
    ("3D ResNet-18 + anchor", "resnet3d__cv5__s*.csv"),
    ("Clinical + topography (R2b)", "baseline_R2b_*__cv5.csv"),
    ("Clinical + volume (R1)", "baseline_R1_clin_volume__cv5.csv"),
    ("Clinical + lesion (R1b)", "baseline_R1b_*__cv5.csv"),
    ("Clinical (R0)", "baseline_R0_clinical__cv5.csv"),
]
nseeds = {}
for name, pat in spec:
    models[name], nseeds[name] = seed_avg(pat)
st = pd.read_csv(f"{RESD}/explain/stacking_oof.csv").set_index("participant_id")
models["Late fusion (image only + clinical)"] = st.p_stack
models["2.5D network, image only"] = st.p_imgonly

df = coh.set_index("participant_id")
for k, v in models.items():
    df[k] = v
df = df.dropna()
y = df.y_poor.values.astype(int)
n = len(y)
print("patients:", n, "events:", y.sum())

rng = np.random.default_rng(SEED)
W = rng.dirichlet(np.ones(n), size=NDRAW)  # NDRAW x n


def weighted_auc(score, y, W):
    o = np.argsort(score, kind="mergesort")
    s, yy, Ww = score[o], y[o], W[:, o]
    neg = Ww * (yy == 0)
    pos = Ww * (yy == 1)
    # tie handling: group equal scores
    _, start, cnt = np.unique(s, return_index=True, return_counts=True)
    cneg = np.cumsum(neg, axis=1)
    below = np.zeros_like(neg)
    gneg = np.add.reduceat(neg, start, axis=1)
    prev = np.concatenate([np.zeros((W.shape[0], 1)), np.cumsum(gneg, axis=1)[:, :-1]], axis=1)
    gid = np.repeat(np.arange(len(start)), cnt)
    below = prev[:, gid] + 0.5 * gneg[:, gid]
    num = (pos * below).sum(1)
    return num / (pos.sum(1) * neg.sum(1))


auc = {k: weighted_auc(df[k].values, y, W) for k in models}
point = {k: weighted_auc(df[k].values, y, np.ones((1, n)) / n)[0] for k in models}

rows = []
for ref in ["Clinical + lesion (R1b)", "CALM-Stroke"]:
    for k in models:
        if k == ref:
            continue
        d = auc[k] - auc[ref]
        r = dict(reference=ref, model=k, n_seeds=nseeds.get(k, 1),
                 auc=point[k], d_mean=d.mean(), d_lo=np.quantile(d, .025), d_hi=np.quantile(d, .975))
        for m in ROPES:
            r[f"p_worse_{m}"] = (d < -m).mean()
            r[f"p_rope_{m}"] = (np.abs(d) <= m).mean()
            r[f"p_better_{m}"] = (d > m).mean()
        r["p_gt0"] = (d > 0).mean()
        rows.append(r)
res = pd.DataFrame(rows)
res.to_csv(f"{OUT}/bayes_rope.csv", index=False, float_format="%.4f")

# LaTeX macros \NBR{key}{field}
keymap = {"CALM-Stroke": "calm", "2.5D MIL + anchor": "mil", "Late fusion (image only + clinical)": "stack",
          "2.5D network, image only": "imgonly", "CALM-Stroke, no auxiliary tasks": "calmnx",
          "Clinical (R0)": "R0", "Clinical + lesion (R1b)": "R1b"}
with open(f"{OUT}/numbers_bayes.tex", "w") as f:
    f.write("%% generated by src/bayes_equivalence.py (Bayesian bootstrap, %d draws, ROPE +/-%.2f)\n" % (NDRAW, ROPE))
    f.write("\\providecommand{\\NBR}[3]{\\csname nbr@#1@#2@#3\\endcsname}\n")
    for _, r in res.iterrows():
        if r.model not in keymap:
            continue
        rk = "vsR1b" if r.reference.startswith("Clinical") else "vscalm"
        for fld, val in [("dmean", r.d_mean), ("dlo", r.d_lo), ("dhi", r.d_hi),
                         ("pbetter", r[f"p_better_{ROPE}"]), ("prope", r[f"p_rope_{ROPE}"]),
                         ("pworse", r[f"p_worse_{ROPE}"]), ("pgtzero", r.p_gt0),
                         ("prope1", r["p_rope_0.01"]), ("prope3", r["p_rope_0.03"]),
                         ("pbetter1", r["p_better_0.01"])]:
            f.write("\\expandafter\\def\\csname nbr@%s@%s@%s\\endcsname{%s}\n" % (keymap[r.model], rk, fld, ("%.3f" % val).replace("-", "$-$")))

# ---------- figure: posterior density + probability bar, two panels ----------
C_W, C_R, C_B = "#eb6834", "#9b9a97", "#2a78d6"   # worse / ROPE / better (diverging + neutral)
INK, INK2 = "#0b0b0b", "#52514e"
plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 7.5, "axes.edgecolor": INK2,
                     "axes.linewidth": 0.6, "xtick.color": INK2, "ytick.color": INK2})
fig, axes = plt.subplots(2, 1, figsize=(7.16, 7.6), gridspec_kw=dict(hspace=0.32))
for ax, ref in zip(axes, ["Clinical + lesion (R1b)", "CALM-Stroke"]):
    sub = res[res.reference == ref].sort_values("d_mean")
    for i, (_, r) in enumerate(sub.iterrows()):
        d = auc[r.model] - auc[ref]
        hist, edges = np.histogram(d, bins=80, range=(-0.13, 0.08), density=True)
        x = 0.5 * (edges[1:] + edges[:-1])
        h = hist / hist.max() * 0.82
        col = np.where(x < -ROPE, C_W, np.where(x > ROPE, C_B, C_R))
        for j in range(len(x) - 1):
            ax.fill_between(x[j:j + 2], i, i + h[j:j + 2], color=col[j], lw=0, alpha=0.9)
        ax.plot(x, i + h, color=INK, lw=0.5)
        ax.plot([r.d_lo, r.d_hi], [i - 0.08, i - 0.08], color=INK, lw=1.0, solid_capstyle="round")
        ax.plot(r.d_mean, i - 0.08, "o", ms=3, color=INK)
        pw, pr, pb = r[f"p_worse_{ROPE}"], r[f"p_rope_{ROPE}"], r[f"p_better_{ROPE}"]
        for xx, v in zip((1.06, 1.18, 1.30), (pw, pr, pb)):
            ax.text(xx, i + 0.2, f"{v:.2f}", fontsize=7, color=INK, va="center", ha="center",
                    transform=ax.get_yaxis_transform(), clip_on=False)
    ax.axvspan(-ROPE, ROPE, color=C_R, alpha=0.12, lw=0)
    ax.axvline(0, color=INK2, lw=0.5, ls=":")
    ax.set_yticks(range(len(sub)))
    ax.set_yticklabels([f"{m} [{k} seeds]" if (k := nseeds.get(m, 1)) > 1 else m for m in sub.model], fontsize=7)
    ax.set_xlim(-0.13, 0.08)
    ax.set_xticks([-0.10, -0.05, 0, 0.05])
    ax.set_ylim(-0.6, len(sub))
    ax.set_xlabel(f"Posterior of $\\Delta$AUC vs {ref.split('(')[-1].rstrip(')') if '(' in ref else ref}")
    for s in ["top", "right", "left"]:
        ax.spines[s].set_visible(False)
    ax.tick_params(axis="y", length=0)
    for xx, lab in zip((1.06, 1.18, 1.30), ("P(<)", "P(≈)", "P(>)")):
        ax.text(xx, len(sub) - 0.1, lab, fontsize=7.5, color=INK2, ha="center", weight="bold",
                transform=ax.get_yaxis_transform(), clip_on=False)
axes[0].set_title("(a) Against the expert-lesion clinical model (R1b)", loc="left", fontsize=8, color=INK)
axes[1].set_title("(b) Against CALM-Stroke", loc="left", fontsize=8, color=INK)
from matplotlib.patches import Patch
fig.legend(handles=[Patch(color=C_W, label=f"worse by more than {ROPE}"),
                    Patch(color=C_R, label=f"practically equivalent (|$\\Delta$| $\\leq$ {ROPE})"),
                    Patch(color=C_B, label=f"better by more than {ROPE}")],
           loc="lower center", ncol=3, frameon=False, fontsize=7, bbox_to_anchor=(0.5, 0.0))
fig.subplots_adjust(left=0.31, right=0.70, bottom=0.08, top=0.96)
fig.savefig(f"{OUT}/fig_bayes_rope.pdf")
fig.savefig(f"{OUT}/fig_bayes_rope.png", dpi=300)
